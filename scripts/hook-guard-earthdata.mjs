// PreToolUse hook (.claude/settings.json, matcher Edit|Write|Bash|PowerShell):
// denies changes to the generated src/earthdata.js — via the file tools or via
// shell writes (redirects, sed/perl -i, tee, cp/mv onto it, rm, Set-Content…).
// Reads and regeneration (node scripts/build-earthdata.mjs) are unaffected.
const F = 'earthdata\\.js';
const END = '(?=$|[\\s\'";&|)])'; // token boundary: not earthdata.js.bak etc.
const fileRe = new RegExp('[\\\\/]' + F + '$', 'i');
const cmdRes = [
  '>{1,2}\\s*[\'"]?[^\\s\'"|;&]*' + F + END,                   // redirect into it
  '\\bsed\\b[^|;&]*\\s-i\\S*[^|;&]*' + F + END,                // sed -i on it
  '\\bperl\\b[^|;&]*\\s-i\\S*[^|;&]*' + F + END,
  '\\b(tee|truncate|sponge|shred)\\b[^|;&]*' + F + END,
  '\\b(mv|cp)\\b\\s+(-\\S+\\s+)*\\S+\\s+[^\\s;&|]*' + F + END, // it as destination
  '\\brm\\b[^|;&]*' + F + END,
  '\\b(set-content|out-file|add-content|copy-item|move-item|remove-item)\\b[^|;&]*' + F + END,
].map((s) => new RegExp(s, 'i'));
let raw = '';
process.stdin.on('data', (c) => (raw += c));
process.stdin.on('end', () => {
  let input = {};
  try { input = JSON.parse(raw).tool_input || {}; } catch {}
  const hit =
    (input.file_path && fileRe.test(input.file_path)) ||
    (input.command && cmdRes.some((r) => r.test(input.command)));
  if (hit) {
    console.log(JSON.stringify({
      hookSpecificOutput: {
        hookEventName: 'PreToolUse',
        permissionDecision: 'deny',
        permissionDecisionReason:
          'src/earthdata.js is generated by scripts/build-earthdata.mjs from Natural Earth. Edit the builder and regenerate; never the output. (If this command only reads it, restructure so the file is not a write target.)',
      },
    }));
  }
});
